"""FDK reconstruction of the 601-view, 1056x1056 real head projections.

The RAW frames are assumed to be float32 line integrals (already corrected),
in view/row/column order. Geometry comes from the five files beside this
script, generated by matrix_to_tigre.py from PMatrix.raw. Run --inspect first.

Example:
    python pipelines/geo/reconstruct_real.py --inspect
    python pipelines/geo/reconstruct_real.py --output output/real_fdk/100446.tif
    python pipelines/geo/reconstruct_real.py --projection-dir PATH --output PATH
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import numpy as np


HERE = Path(__file__).resolve().parent
DEFAULT_PROJECTIONS = Path(
    # "D:/desktop/stent/interior/真实数据/real_data_2/data/new/head/proj/100446_proj"
    r"D:\desktop\stent\interior\真实数据\real_data_2\data\new\stent\proj\103693"
)
FRAME_NAME = re.compile(r"IMG(\d+)_(\d+)-(\d+)\.raw", re.IGNORECASE)


def find_projections(directory: Path) -> tuple[list[Path], tuple[int, int]]:
    """Sort views by IMG number and verify the RAW dimensions and byte counts."""
    if not directory.is_dir():
        raise FileNotFoundError(f"Projection directory not found: {directory}")
    indexed = []
    for path in directory.glob("*.raw"):
        match = FRAME_NAME.fullmatch(path.name)
        if match is None:
            raise ValueError(f"Unrecognized projection name: {path.name}")
        index, rows, columns = map(int, match.groups())
        if path.stat().st_size != rows * columns * np.dtype("<f4").itemsize:
            raise ValueError(f"Projection size does not match float32 dimensions: {path}")
        indexed.append((index, (rows, columns), path))
    if not indexed:
        raise FileNotFoundError(f"No RAW projections found in {directory}")
    indexed.sort(key=lambda item: item[0])
    numbers = [item[0] for item in indexed]
    if numbers != list(range(1, len(indexed) + 1)):
        raise ValueError("Projection IMG numbers must be consecutive from 001")
    shape = indexed[0][1]
    if any(item[1] != shape for item in indexed):
        raise ValueError("Projection dimensions differ between views")
    return [item[2] for item in indexed], shape


def read_projections(files: list[Path], shape: tuple[int, int]) -> np.ndarray:
    """Load pre-log-corrected float32 projections into a TIGRE stack."""
    stack = np.empty((len(files), *shape), dtype=np.float32)
    for index, path in enumerate(files):
        frame = np.fromfile(path, dtype="<f4").reshape(shape)
        if not np.all(np.isfinite(frame)):
            raise ValueError(f"Projection contains NaN/Inf: {path}")
        stack[index] = frame
    return stack


def load_geometry(
    directory: Path,
    n_views: int,
    detector_shape: tuple[int, int],
    *,
    detector_pitch_mm: float = 0.150,
    volume_shape: tuple[int, int, int] = (533, 512, 512),
    voxel_mm: float = 0.188946,
):
    """Build TIGRE geometry; array order is (view, V/row, U/column)."""
    if detector_pitch_mm <= 0 or voxel_mm <= 0 or any(n <= 0 for n in volume_shape):
        raise ValueError("Detector pitch, voxel spacing and volume shape must be positive")
    series = {}
    for name in ("angle", "sod", "sdd", "uoffset", "voffset"):
        path = directory / f"{name}.raw"
        values = np.fromfile(path, dtype="<f4")
        if values.size != n_views:
            raise ValueError(f"{path.name}: expected {n_views} values, got {values.size}")
        if not np.all(np.isfinite(values)):
            raise ValueError(f"{path.name} contains NaN/Inf")
        series[name] = values
    if np.any(series["sod"] <= 0) or np.any(series["sdd"] <= series["sod"]):
        raise ValueError("Each view needs 0 < SOD < SDD")

    import tigre  # Lazy import lets --help and file checks run without TIGRE.

    geo = tigre.geometry(mode="cone")
    geo.DSO = series["sod"]
    geo.DSD = series["sdd"]
    geo.nDetector = np.asarray(detector_shape, dtype=np.int32)
    geo.dDetector = np.full(2, detector_pitch_mm, dtype=np.float32)
    geo.sDetector = geo.nDetector * geo.dDetector
    geo.nVoxel = np.asarray(volume_shape, dtype=np.int32)
    geo.dVoxel = np.full(3, voxel_mm, dtype=np.float32)
    geo.sVoxel = geo.nVoxel * geo.dVoxel
    geo.offOrigin = np.zeros(3, dtype=np.float32)
    # matrix_to_tigre.py writes pixel offsets relative to the 1056-pixel center.
    # TIGRE wants millimetres and (V, U) column order for each view.
    geo.offDetector = np.column_stack(
        (series["voffset"], series["uoffset"])
    ).astype(np.float32) * np.float32(detector_pitch_mm)
    geo.rotDetector = np.zeros((n_views, 3), dtype=np.float32)
    geo.COR = 0.0
    geo.accuracy = 0.5
    angles = np.ascontiguousarray(series["angle"] - series["angle"][0])
    return geo, angles


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--projection-dir", type=Path, default=DEFAULT_PROJECTIONS)
    parser.add_argument("--geometry-dir", type=Path, default=HERE)
    parser.add_argument("--output", type=Path,
                        help="Output TIFF; defaults to output/real_fdk/<projection folder>_fdk.tif")
    parser.add_argument("--detector-pitch-mm", type=float, default=0.150)
    parser.add_argument("--voxel-mm", type=float, default=0.188946)
    parser.add_argument("--volume-shape", type=int, nargs=3, default=(533, 512, 512),
                        metavar=("Z", "Y", "X"))
    parser.add_argument("--filter", choices=("hann", "hamming", "cosine", "ram_lak", "shep_logan"),
                        default="hann")
    parser.add_argument("--inspect", action="store_true", help="Check geometry without loading frames or using GPU")
    parser.add_argument("--overwrite", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    output = args.output or Path("output/real_fdk") / f"{args.projection_dir.name}_fdk_stent.tif"
    files, detector_shape = find_projections(args.projection_dir)
    if detector_shape != (1056, 1056):
        raise ValueError(f"Expected project-1 1056x1056 projections, got {detector_shape}")
    geo, angles = load_geometry(
        args.geometry_dir, len(files), detector_shape,
        detector_pitch_mm=args.detector_pitch_mm,
        volume_shape=tuple(args.volume_shape), voxel_mm=args.voxel_mm,
    )
    info = {
        "views": len(files),
        "projection_shape": list(detector_shape),
        "angle_span_deg": float(np.rad2deg(angles[-1] - angles[0])),
        "DSO_mm_range": [float(np.min(geo.DSO)), float(np.max(geo.DSO))],
        "DSD_mm_range": [float(np.min(geo.DSD)), float(np.max(geo.DSD))],
        "detector_pitch_mm": args.detector_pitch_mm,
        "offDetector_mm_VU_range": [
            [float(np.min(geo.offDetector[:, axis])), float(np.max(geo.offDetector[:, axis]))]
            for axis in (0, 1)
        ],
        "volume_shape_ZYX": list(map(int, geo.nVoxel)),
        "voxel_mm": args.voxel_mm,
        "geometry_dir": str(args.geometry_dir),
        "output": str(output),
    }
    print(json.dumps(info, ensure_ascii=False, indent=2), flush=True)
    if args.inspect:
        return 0
    if output.exists() and not args.overwrite:
        raise FileExistsError(f"Output already exists: {output}; pass --overwrite")

    import tifffile
    import tigre.algorithms as algorithms

    projections = read_projections(files, detector_shape)
    image = algorithms.fdk(projections, geo, angles, filter=args.filter, dowang=False)
    output.parent.mkdir(parents=True, exist_ok=True)
    tifffile.imwrite(output, np.asarray(image, dtype=np.float32))
    print(f"Saved {output} with shape {image.shape}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
